constexpr const char* kStageDir = "var/lib/cccu";

// Unmounts /mnt (and the bind mounts below it) however we leave the function.
// The install log is copied onto the new system first, so it can be read after the reboot.
struct MountGuard {
    ~MountGuard() {
        if (dry_run()) return;
        if (!log_path().empty() && !query({"findmnt", "-n", drive::kTarget}).empty()) {
            std::error_code ec;
            const fs::path dir = fs::path(drive::kTarget) / "var/log/cccu";
            fs::create_directories(dir, ec);
            if (!ec) fs::copy_file(log_path(), dir / "install.log", fs::copy_options::overwrite_existing, ec);
        }
        drive::unmount();
    }
};

std::string find_live_rootfs() {
    // archiso layouts, and the layout used by the old installerlinux script.
    for (const char* candidate : {"/run/archiso/bootmnt/arch/x86_64/airootfs.sfs",
                                  "/run/archiso/bootmnt/arch/x86_64/airootfs.erofs",
                                  "/run/arch/bootmnt/LiveOS/rootfs.img"}) {
        std::error_code ec;
        if (fs::is_regular_file(candidate, ec)) return candidate;
    }
    return {};
}

std::string package_for(const std::string& tool) {
    if (tool == "unsquashfs") return "squashfs-tools";
    if (tool == "fsck.erofs") return "erofs-utils";
    if (tool == "mkfs.vfat") return "dosfstools";
    if (tool == "mkfs.btrfs") return "btrfs-progs";
    if (tool == "mkfs.ext4") return "e2fsprogs";
    return tool;  // parted, tar, zstd, xz, rsync, ...
}

// Packages from `candidates` that are NOT installed, from pacman's local database
// (`pacman -T` never uses the network and prints exactly the unmet ones).
std::vector<std::string> missing_packages(const std::vector<std::string>& candidates, const std::string& root = "") {
    std::vector<std::string> argv = {"pacman", "-T"};
    if (!root.empty()) {
        argv.push_back("--root");
        argv.push_back(root);
    }
    argv.insert(argv.end(), candidates.begin(), candidates.end());
    RunOptions probe;
    probe.mutating = false;
    probe.capture = true;
    probe.quiet = true;
    std::vector<std::string> missing;
    for (const auto& line : split_lines(run(argv, probe).out)) {
        if (!trim(line).empty()) missing.push_back(trim(line));
    }
    return missing;
}

// Installs only what is not installed yet, without a system upgrade. The package databases are
// refreshed (-y) only when installing from the existing ones fails.
Result install_packages(const std::vector<std::string>& packages) {
    if (packages.empty()) return {};
    std::vector<std::string> argv = {"pacman", "-S", "--needed", "--noconfirm"};
    argv.insert(argv.end(), packages.begin(), packages.end());
    if (run(argv).ok()) return {};
    info("Retrying with refreshed package databases...");
    argv[1] = "-Sy";
    if (!run(argv).ok()) return fail("pacman could not install the required packages");
    return {};
}

// The live ISO is Arch, so pacman is the way to get missing tools.
Result install_live_tools(const std::vector<std::string>& tools) {
    std::vector<std::string> wanted;
    for (const auto& tool : tools) {
        if (!have_command(tool)) wanted.push_back(package_for(tool));
    }
    const auto missing = missing_packages(wanted);
    if (missing.empty()) return {};
    step("Installing tools in the live environment");
    return install_packages(missing);
}

Result in_chroot(const std::string& script) {
    if (!run({"chroot", drive::kTarget, "/bin/bash", "-c", script}).ok()) return fail("a step inside the new system failed");
    return {};
}

Result bind_mounts() {
    const std::string target = drive::kTarget;
    for (const char* dir : {"dev", "proc", "sys", "run"}) {
        const std::string mount_point = target + "/" + dir;
        if (!run({"mount", "--rbind", std::string("/") + dir, mount_point}).ok()) return fail("could not bind-mount /" + std::string(dir));
        run({"mount", "--make-rslave", mount_point});
    }
    return {};
}

std::string uuid_of(const std::string& device) { return query({"blkid", "-s", "UUID", "-o", "value", device}); }

Result write_fstab(const Options& o, const drive::Layout& layout) {
    const std::string root_uuid = uuid_of(layout.root_part);
    const std::string efi_uuid = uuid_of(layout.efi_part);
    if (root_uuid.empty() || efi_uuid.empty()) return fail("could not read the partition UUIDs");

    std::string fstab = "# Generated by cccu\n";
    if (o.fs == "btrfs") {
        for (const auto& sv : drive::kBtrfsSubvolumes) {
            fstab += "UUID=" + root_uuid + " " + sv.mount_point + " btrfs subvol=" + sv.name +
                     drive::btrfs_compress_options(o.compression) + " 0 0\n";
        }
    } else {
        fstab += "UUID=" + root_uuid + " / ext4 defaults 0 1\n";
    }
    fstab += "UUID=" + efi_uuid + " /boot/efi vfat umask=0077 0 2\n";
    return write_text(fs::path(drive::kTarget) / "etc/fstab", fstab);
}

std::string dm_name(DisplayManager dm) {
    switch (dm) {
        case DisplayManager::Sddm: return "sddm";
        case DisplayManager::PlasmaLogin: return "plasmalogin";
        case DisplayManager::None: return "none";
        case DisplayManager::Auto: break;
    }
    return "auto";
}

// Copies the desktop image + this program onto the host and arranges for the container to be
// created on the host's first boot (Incus cannot run inside the chroot).
Result stage_desktop(const Options& o) {
    const fs::path target = drive::kTarget;
    const fs::path stage = target / kStageDir;
    std::error_code ec;
    fs::create_directories(stage, ec);

    const std::string file = fs::path(o.image).filename().string();
    if (file.find(' ') != std::string::npos) return fail("Rename the image so its file name has no spaces: " + file);
    const std::string staged = "/" + std::string(kStageDir) + "/" + file;

    step("Copying the desktop image onto the new system");
    if (auto r = copy_file_progress(o.image, (stage / file).string()); !r) return r;

    step("Copying the installer onto the new system");
    const fs::path self = fs::read_symlink("/proc/self/exe", ec);
    if (ec) return fail("could not find the installer program: " + ec.message());
    if (auto r = copy_file_progress(self.string(), (target / "usr/local/bin/cccu").string(), "755"); !r) {
        return fail("could not copy the installer onto the new system: " + r.error());
    }

    std::string command = "/usr/local/bin/cccu " + o.name + " --image " + staged + " --yes";
    if (!o.user.empty()) command += " --user " + o.user;
    if (!o.container_user.empty()) command += " --container-user " + o.container_user;
    // What was answered at the install: the container storage is created from these on the first boot.
    command += " --size " + o.container_size;
    command += " --compress " + (o.compression.empty() ? std::string("none") : o.compression);
    if (o.immutable) command += " --immutable";
    if (o.dm != DisplayManager::Auto) command += " --dm " + dm_name(o.dm);
    command += " --display " + std::string(to_string(o.display));
    // Native mode: once the container runs, its display manager owns VT1, so the host's getty goes.
    const std::string mask_getty =
        o.display == Display::Native ? "ExecStartPost=/usr/bin/systemctl mask --now getty@tty1.service\n" : "";

    const std::string unit =
        "[Unit]\n"
        "Description=CCCU: create the desktop container (first boot)\n"
        "Wants=network-online.target\n"
        "After=network-online.target getty@tty1.service\n"
        "Conflicts=getty@tty1.service\n"
        "ConditionPathExists=" + staged + "\n\n"
        "[Service]\n"
        "Type=oneshot\n"
        "TimeoutStartSec=infinity\n"
        // A real terminal on VT1 (not the journal): CCCU draws its colours, progress bar and live
        // status line there, and boot messages are silenced meanwhile so they do not scribble over it.
        "StandardInput=tty\n"
        "StandardOutput=tty\n"
        "StandardError=tty\n"
        "TTYPath=/dev/tty1\n"
        "TTYReset=yes\n"
        "TTYVHangup=yes\n"
        "Environment=TERM=linux\n"
        "ExecStartPre=-/usr/bin/kill -s RTMIN+21 1\n"
        "ExecStart=" + command + "\n" + mask_getty +
        "ExecStartPost=/usr/bin/rm -f " + staged + "\n"
        "ExecStartPost=/usr/bin/systemctl disable cccu-firstboot.service\n"
        "ExecStopPost=-/usr/bin/kill -s RTMIN+20 1\n\n"
        "[Install]\n"
        "WantedBy=multi-user.target\n";
    if (auto r = write_text(target / "etc/systemd/system/cccu-firstboot.service", unit); !r) return r;
    run({"systemctl", std::string("--root=") + drive::kTarget, "enable", "cccu-firstboot.service"});
    return {};
}

