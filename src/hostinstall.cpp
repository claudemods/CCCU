Result install_to_drive(Options o) {
    if (!is_root()) return fail("This must run as root from the live environment.");
    if (o.drive.empty()) return fail("--drive <device> is required, e.g. --drive /dev/sda");
    if (o.name.empty()) o.name = "desktop";
    std::error_code ec;
    if (o.image.empty() || !fs::is_regular_file(o.image, ec)) return fail("--image <desktop image> is required (made with --export)");
    if (!dry_run() && !fs::exists("/sys/firmware/efi")) return fail("Not booted in UEFI mode; reboot the live ISO in UEFI mode.");

    std::vector<std::string> tools = drive::required_tools(o);
    if (!o.clone_system && o.host_image.empty()) {
        o.host_image = find_live_rootfs();
        if (o.host_image.empty()) {
            info("No live ISO image found and no --host-image given: using the running system as the tty host.");
            o.clone_system = true;
        }
    }
    if (o.clone_system) {
        info("Host (tty) system:    clone of the running system");
        tools.push_back("rsync");
        if (fs::exists("/run/archiso", ec)) {
            warn("The running system is an Arch live ISO: its initramfs setup (archiso hooks) may not boot "
                 "from a drive. Prefer cloning an installed system or use --host-image.");
        }
    } else {
        if (!fs::is_regular_file(o.host_image, ec)) return fail("Host image not found: " + o.host_image);
        info("Host (tty) system:    image " + o.host_image);
        const auto host_tools = sources::image_tools(o.host_image);
        tools.insert(tools.end(), host_tools.begin(), host_tools.end());
    }
    info("Desktop image:        " + o.image);
    if (auto r = install_live_tools(tools); !r) return r;

    drive::Layout layout;
    MountGuard guard;
    if (auto r = drive::prepare(o, layout); !r) return r;

    step("Installing the host system");
    if (o.clone_system) {
        Options clone = o;
        clone.keep_kernel = true;   // the host needs its kernel in /boot
        clone.keep_caches = false;
        if (auto r = sources::clone_running(clone, drive::kTarget); !r) return r;
    } else if (auto r = sources::extract_image(o.host_image, drive::kTarget); !r) {
        return r;
    }
    if (!dry_run()) {
        bool has_kernel = false;
        for (const auto& entry : fs::directory_iterator(fs::path(drive::kTarget) / "boot", ec)) {
            if (entry.path().filename().string().rfind("vmlinuz", 0) == 0) has_kernel = true;
        }
        if (!has_kernel) return fail("The host image has no kernel in /boot (vmlinuz-*). Use an image that contains one.");
    }
    if (auto r = drive::mount_efi(layout); !r) return r;
    if (!dry_run()) {
        if (auto r = write_fstab(o, layout); !r) return r;
    }
    if (auto r = bind_mounts(); !r) return r;

    if (dry_run()) {
        info("(dry run) would now: install incus in the new system, configure it as a tty host,");
        info("(dry run) install GRUB, set the root password and stage the desktop container.");
        return {};
    }

    // Which system is this host base? The package manager, initramfs tool and GRUB commands depend on it.
    const distro::Info base = distro::detect(drive::kTarget);
    if (base.family == distro::Family::Unsupported) {
        for (const auto& line : distro::supported_list()) info("  " + line);
        return fail("Cannot use " + base.name + " as the tty host: " + base.reason + ".");
    }
    info("Host base:            " + base.name + " - " + distro::family_name(base.family));

    step("Installing Incus and what the host needs in the new system");
    // resolv.conf may be a symlink in the new system: replace it by a real file so the chroot has DNS.
    std::filesystem::remove(std::string(drive::kTarget) + "/etc/resolv.conf", ec);
    if (auto r = copy_file_progress("/etc/resolv.conf", std::string(drive::kTarget) + "/etc/resolv.conf"); !r) warn(r.error());
    // The host only needs: Incus (+ btrfs-progs for the container's own btrfs storage), the bootloader,
    // whatever unpacks the desktop image, and what the Container Plasma session needs (SDDM, cage, GPU
    // drivers, audio). Generic names; distro.cpp maps them to the base's package names.
    std::vector<std::string> generic = {"incus", "grub", "efibootmgr", "tar", "btrfs-progs"};
    for (const auto& tool : sources::image_tools(o.image)) generic.push_back(package_for(tool));
    for (const char* pkg : {"sddm", "qt6-wayland", "cage", "mesa", "pipewire", "pipewire-pulse", "wireplumber"}) generic.emplace_back(pkg);
    // Packages already installed in the new system are skipped; only the missing ones are installed.
    if (auto r = in_chroot(distro::install_missing_script(base.family, distro::map_packages(base.family, generic))); !r) return r;
    if (auto r = rootfs::adapt_host(drive::kTarget, o); !r) return r;

    if (!o.user.empty()) {
        const auto allowed = [](char c) { return std::islower(static_cast<unsigned char>(c)) || std::isdigit(static_cast<unsigned char>(c)) || c == '_' || c == '-'; };
        if (!std::all_of(o.user.begin(), o.user.end(), allowed)) {
            return fail("Invalid user name '" + o.user + "' (lowercase letters, digits, - and _ only).");
        }
        step("Desktop user '" + o.user + "' on the host");
        const bool missing = ("\n" + read_text(fs::path(drive::kTarget) / "etc/passwd")).find("\n" + o.user + ":") == std::string::npos;
        // Needs the incus-admin group: the session starts and talks to the container as this user.
        if (auto r = in_chroot(
                "user=" + o.user + "\n"
                "id \"$user\" >/dev/null 2>&1 || useradd -m -s /bin/bash \"$user\"\n"
                "for g in incus-admin wheel video audio input render; do\n"
                "    getent group $g >/dev/null && usermod -aG $g \"$user\" || true\n"
                "done\n");
            !r) {
            return r;
        }
        if (missing) {
            info("New host user: set its password.");
            if (!o.user_password.empty()) {
                if (!set_password(drive::kTarget, o.user, o.user_password)) return fail("could not set the password of " + o.user);
            } else {
                RunOptions tty;
                tty.interactive = true;
                run({"chroot", drive::kTarget, "passwd", o.user}, tty);
            }
        }
    }

    // Show boot and first-boot progress on the console instead of a blank "quiet" screen.
    {
        const fs::path grub_default = fs::path(drive::kTarget) / "etc/default/grub";
        std::string text = read_text(grub_default);
        for (const std::string word : {" quiet", " splash"}) {
            for (std::size_t pos; (pos = text.find(word)) != std::string::npos;) text.erase(pos, word.size());
        }
        if (!text.empty()) {
            if (auto written = write_text(grub_default, text); !written) warn(written.error());
        }
    }

    step("Installing the bootloader");
    if (auto r = in_chroot(distro::initramfs_and_boot_script(base.family)); !r) return r;

    step("Set the root password for the new host (tty login)");
    if (!o.root_password.empty()) {
        if (!set_password(drive::kTarget, "root", o.root_password)) return fail("could not set the root password");
    } else {
        RunOptions terminal;
        terminal.interactive = true;
        run({"chroot", drive::kTarget, "passwd", "root"}, terminal);
    }

    if (auto r = stage_desktop(o); !r) return r;

    ok("Installation complete.");
    info("Reboot into the new system. It boots to a text console; on that first boot it creates the");
    info("desktop container from your image. CCCU shows live progress on that screen (VT1); the log is");
    info("also in: journalctl -u cccu-firstboot -f (tty2),");
    info("then the container's login screen appears on VT1. Log in on tty2 as root for the host.");
    info("Logs on the new system:  /var/log/cccu/install.log   (this install)");
    info("                         /var/log/cccu/container.log (container creation + diagnostics)");
    return {};
}

